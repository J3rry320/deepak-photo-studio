export async function seedPackages(disconnectOnFinish = true) {
  if (mongoose.connection.readyState === 0) {
    console.log('[Seed:Packages] Connecting to MongoDB...');
    await mongoose.connect(MONGODB_URI);
  }

  try {
    for (const pkg of initialPackages) {
      await Package.findOneAndUpdate(
        { slug: pkg.slug },
        { $set: pkg },
        { upsert: true, new: true }
      );
      console.log(`[Seed:Packages] Upserted package: ${pkg.slug}`);
    }
    console.log('[Seed:Packages] Successfully seeded all studio wedding packages with bilingual Odia/English data!');
  } finally {
    if (disconnectOnFinish) {
      await mongoose.disconnect();
      console.log('[Seed:Packages] Disconnected.');
    }
  }
}

if (require.main === module) {
  seedPackages().catch((err) => {
    console.error('[Seed:Packages] Error:', err);
    process.exit(1);
  });
}
